/** Exact 0-based `Structure.id` ranges computed deterministically for each perimeter wall section. */
export function computeWallSectionIds(): Record<WallSectionKey, number[]> {
  const out: Record<WallSectionKey, number[]> = {
    south_section_b: [],
    south_west_gate: [],
    south_east_gate: [],
    west_flank_gate: [],
    east_flank_gate: [],
    south_curtain: [],
    west_curtain: [],
    east_curtain: [],
    north_curtain: [],
    north_gate: [],
  };
  let cursor = 0;
  for (const run of HALCYON_PERIMETER_WALLS) {
    const count = wallRunSegmentCount(run);
    for (let i = 0; i < count; i++) {
      out[run.section].push(cursor++);
    }
  }
  return out;
}

export const HALCYON_WALL_IDS_BY_SECTION = computeWallSectionIds();

