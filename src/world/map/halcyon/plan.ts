export interface PerimeterWallRun {
  readonly id: string;
  readonly section: WallSectionKey;
  readonly kind: 'wall' | 'gate';
  readonly ax: number;
  readonly az: number;
  readonly bx: number;
  readonly bz: number;
  readonly tier: 1 | 2;
  readonly label: string;
  readonly value: number;
}

/** Exact segment count generated by `MapSpec.wall` / `MapSpec.wallGate` for a run. */
export function wallRunSegmentCount(run: PerimeterWallRun): number {
  if (run.kind === 'gate') return 1;
  return Math.max(1, Math.round(Math.hypot(run.bx - run.ax, run.bz - run.az) / WALL.segment));
}

