/** Optional `?vehicle=jackal|aegis|kestrel|viper|bastion` URL parameter to start a run seated in that vehicle. */
export const VEHICLE_ASKED: DriveVehicleId | null = (() => {
  if (typeof location === 'undefined') return null;
  const v = new URLSearchParams(location.search).get('vehicle');
  if (v === 'jackal' || v === 'aegis' || v === 'kestrel' || v === 'viper' || v === 'bastion') return v;
  return null;
})();
