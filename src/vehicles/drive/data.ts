/** Optional `?vehicle=<id>` URL query parameter for instant spawn & board! */
export const VEHICLE_ASKED: DriveVehicleId | null = (() => {
  if (typeof location === 'undefined') return null;
  const raw = new URLSearchParams(location.search).get('vehicle')?.toLowerCase();
  if (!raw) return null;
  return (DRIVE_VEHICLE_ORDER as readonly string[]).includes(raw) ? (raw as DriveVehicleId) : null;
})();
