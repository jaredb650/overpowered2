// Writes the recording scripts for sections 18, 19 and 22 from src/enemies/commander/lines.ts and the mission's own lines. Nothing here
// talks to ElevenLabs: the lead does.
//
//   nice -n 19 npx tsx tools/scripts/voice-script.ts
//
// docs/voice/commander-script.csv   one row per take: file, speaker, voice, tag, text as spoken
// docs/voice/commander-script.md    the same for a person to read, plus what stays as text
// docs/voice/mission-script.csv     the Outpost mission, in the order it is played
// docs/voice/mission-script.md      the same for a person to read
//
// Recordings go in public/audio/voice/<file>.mp3, and their names go in public/audio/voice/manifest.json. Playback does the rest.
import { mkdirSync, writeFileSync } from 'node:fs';
import { OUTPOST_LINES } from '../../src/campaign/missions/outpost.lines';
import { COUNT_BANDS, LINES, NAMES, ROOM_WORDS, slotsOf, SQUAD_WORDS, textOnly, topicOf, WEAPON_WORDS, type Line, type Speaker } from '../../src/enemies/commander/lines';

const VOICE: Record<Speaker, string> = { commander: 'the void', intercept: 'the void', council: 'shodan', radio: 'radio crew' };

/** Section 19: the Commander's tag is [EVIL] plus the line's own emotion. */
const tag = (l: Line): string => (l.speaker === 'commander' || l.speaker === 'intercept' ? `[EVIL][${l.emotion}]` : `[${l.emotion}]`);

interface Take {
  file: string;
  line: Line;
  spoken: string;
}

function takes(line: Line): Take[] {
  const slots = slotsOf(line.text);
  if (slots.length === 0) return [{ file: line.id, line, spoken: line.text }];
  const slot = slots[0]!;
  const fill = (word: string): string => {
    const said = line.text.replaceAll(`{${slot}}`, word);
    return said[0]!.toUpperCase() + said.slice(1);
  };
  const key = (k: string): string => `${line.id}~${k.replace(/ /g, '_')}`;
  if (slot === 'weapon') return Object.keys(WEAPON_WORDS).map(id => ({ file: key(id), line, spoken: fill(WEAPON_WORDS[id]!) }));
  if (slot === 'room') return ROOM_WORDS.map(r => ({ file: key(r), line, spoken: fill(r) }));
  if (slot === 'name') return NAMES.map(n => ({ file: key(n), line, spoken: fill(n) }));
  if (slot === 'squad') return SQUAD_WORDS.map(n => ({ file: key(n), line, spoken: fill(n) }));
  const topic = topicOf(line.id);
  const bands = topic ? COUNT_BANDS[topic] : undefined;
  if (!bands) throw new Error(`${line.id} has a number and no bands`);
  return bands.map(([n, word]) => ({ file: key(String(n)), line, spoken: fill(word) }));
}

const csv = (s: string): string => `"${s.replace(/"/g, '""')}"`;
const recorded = LINES.filter(l => !textOnly(l) && l.speaker !== 'radio');
const all = recorded.flatMap(takes);
const stayText = LINES.filter(l => textOnly(l) || l.speaker === 'radio');

mkdirSync('docs/voice', { recursive: true });
writeFileSync('docs/voice/commander-script.csv', [
  'file,speaker,voice,tag,text',
  ...all.map(t => [csv(t.file), t.line.speaker, csv(VOICE[t.line.speaker]), tag(t.line), csv(t.spoken)].join(',')),
].join('\n') + '\n');

const groups = new Map<string, Take[]>();
for (const t of all) {
  const key = t.line.id.split('.').slice(0, 2).join('.');
  groups.set(key, [...(groups.get(key) ?? []), t]);
}
const count = (s: Speaker): number => all.filter(t => t.line.speaker === s).length;
const body = [
  '# Commander and Council: recording script',
  '',
  'Generated by `tools/scripts/voice-script.ts` from `src/enemies/commander/lines.ts`. Edit the lines there and run it again, never this file.',
  '',
  `${recorded.length} lines, ${all.length} takes: ${count('commander')} Commander, ${count('intercept')} intercept, ${count('council')} Council.`,
  'Voices: the Commander and the intercepts are "the void", the Council is "shodan". The tag column goes in front of the text.',
  'A take for a line with a number says the band, not the real figure: the box still prints the real one.',
  '',
  ...[...groups.entries()].flatMap(([group, list]) => [
    `## ${group}`, '', '| File | Tag | Text |', '|---|---|---|',
    ...list.map(t => `| \`${t.file}\` | ${tag(t.line)} | ${t.spoken.replace(/\|/g, '\\|')} |`), '',
  ]),
  '## Stays as text',
  '',
  'Radio chatter and any line with two slots. Too dynamic or too minor to record.',
  '',
  ...stayText.map(l => `- \`${l.id}\`: ${l.text}`),
  '',
];
writeFileSync('docs/voice/commander-script.md', body.join('\n'));

// Every mission line is one take, because a mission's words are written out in full. Radio is the pilot here, and he gets recorded.
const row = (l: Line): string => [csv(l.id), l.speaker, csv(VOICE[l.speaker]), tag(l), csv(l.text)].join(',');
writeFileSync('docs/voice/mission-script.csv', ['file,speaker,voice,tag,text', ...OUTPOST_LINES.map(row)].join('\n') + '\n');

const mission = OUTPOST_LINES.filter(l => l.speaker !== 'intercept');
const speakers = (['council', 'commander', 'radio'] as const).map(s => `${mission.filter(l => l.speaker === s).length} ${s === 'radio' ? 'Pilot' : s === 'council' ? 'Council' : 'Commander'}`);
writeFileSync('docs/voice/mission-script.md', [
  '# The Outpost mission: recording script',
  '',
  'Generated by `tools/scripts/voice-script.ts` from `src/campaign/missions/outpost.lines.ts`. Edit the lines there and run it again, never this file. docs/campaign/MISSION.md has each line in its place in the story.',
  '',
  `${OUTPOST_LINES.length} lines, one take each, in the order they are played: ${speakers.join(', ')}.`,
  'Voices: the Commander is "the void", the Council is "shodan", the pilot is a radio voice still to be chosen. The tag column goes in front of the text.',
  'The file is the line id, so a take goes in as `public/audio/voice/<file>.mp3` with its name listed in `public/audio/voice/manifest.json`. A line with no take shows its subtitle and plays nothing.',
  '',
  '| File | Speaker | Tag | Text |',
  '|---|---|---|---|',
  ...OUTPOST_LINES.map(l => `| \`${l.id}\` | ${l.speaker} | ${tag(l)} | ${l.text.replace(/\|/g, '\\|')} |`),
  '',
].join('\n'));
console.log(JSON.stringify({ lines: LINES.length, recorded: recorded.length, takes: all.length, text: stayText.length, mission: OUTPOST_LINES.length }));
